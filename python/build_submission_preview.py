# mapa nome -> CDTUP e coortes de 2011, como em R/15_event_study.R
BASE_2011 = [("BRSSZ", "Santos", "2011-08-01"), ("BRRIO", "Rio de Janeiro", "2011-08-15"),
             ("BRVIX", "Vitória", "2011-09-10")]


def esc(x: str) -> str:
    for ch in "&%$#_{}":
        x = x.replace(ch, "\\" + ch)
    return x


def tabela_tex(linhas, cab, caption, label, align, notas):
    corpo = [" & ".join(esc(c) for c in cab) + " \\\\", "\\midrule"]
    corpo += [" & ".join(esc(c) for c in l) + " \\\\" for l in linhas]
    return "\n".join([
        "\\begin{table}[htbp]", "\\centering", "\\small", f"\\caption{{{caption}}}", f"\\label{{{label}}}",
        f"\\begin{{tabular}}{{{align}}}", "\\toprule", *corpo, "\\bottomrule", "\\end{tabular}",
        "\\par\\vspace{2mm}", "\\begin{minipage}{\\textwidth}\\footnotesize", notas, "\\end{minipage}",
        "\\end{table}", ""])


def quadro_tabela(caption, label):
    return "\n".join([
        "\\begin{table}[htbp]", "\\centering", f"\\caption{{{caption}}}", f"\\label{{{label}}}",
        "\\fbox{\\parbox{0.9\\textwidth}{\\centering\\vspace{1.5em}\\small\\itshape Table generated by the "
        "estimation pipeline from the project database (\\texttt{targets::tar\\_make()}).\\vspace{1.5em}}}",
        "\\end{table}", ""])


def mapa_cdtup():
    txt = (RAIZ / "R" / "15_event_study.R").read_text(encoding="utf-8")
    bloco = txt[txt.index("NOME_CDTUP <- c("):txt.index("montar_coortes")]
    return dict(re.findall(r'"([^"]+)"="(BR[A-Z0-9]*)"', bloco)), txt


def coortes_e_registro():
    nome2cd, txt = mapa_cdtup()
    with open(RAIZ / "data" / "metadata" / "psp_portarias_dou.csv", encoding="utf-8") as f:
        dou = list(csv.DictReader(f, delimiter=";"))
    linhas, vistos = [], set()
    for r in dou:
        for porto in [p.strip() for p in re.split(r",|\se\s", r["portos"]) if p.strip()]:
            cd = nome2cd.get(porto)
            if cd and cd not in vistos:
                vistos.add(cd)
                linhas.append((r["data_ato"], porto, "SEP Ordinance " + r["portaria"].replace("SEP-", ""),
                               r["publicado_em"] or "---", r["migracao_definitiva_ate"] or "---", "High"))
    for cd, porto, data in BASE_2011:
        if cd not in vistos:
            vistos.add(cd)
            ato = ("Official production notice (SEP Ordinance 106/2011 not retrieved)" if cd == "BRSSZ"
                   else "Official production notice")
            linhas.append((data, porto, ato, "---", "---", "Medium"))
    linhas.sort()
    pub = re.findall(r'"(BR[A-Z0-9]*)"', txt[txt.index("PORTOS_PUBLICOS <- c("):txt.index("CODIGOS_NAO_CLASSIFICADOS")])
    cd2nome = {}
    for n, c in nome2cd.items():
        cd2nome.setdefault(c, n)
    sem = sorted(cd2nome.get(c, c) for c in pub if c not in vistos)
    return linhas, sem


def tab15(linhas, sem):
    rows = [(p, a, d, pb, m, c) for d, p, a, pb, m, c in linhas]
    notas = ("Treatment date is the date of the act that made the use of the system mandatory, never the announcement. "
             "High: full text of the ordinance retrieved from the Official Gazette; Medium: official notice of entry into "
             "production without the full text of the act. Migration deadline: date set by the ordinance for the definitive "
             "migration of procedures to the system. Public ports without a dated act, excluded from estimation: "
             + esc(", ".join(sem)) + ". Source: \\texttt{data/metadata/psp\\_portarias\\_dou.csv}.")
    return tabela_tex(rows, ["Port", "Act", "Date of act", "Published", "Migration deadline", "Confidence"],
                      "Registry of adoption dates of the Porto Sem Papel single window", "tab:registry",
                      "p{2.6cm}p{4.4cm}llll", notas)


